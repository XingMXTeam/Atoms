import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
const base = 'http://localhost:3000';
const out = '/Users/felix/Documents/atoms-worktrees/demo/.harness/tasks/generate-loop/evidence/c2-20261123';
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1280, height: 800 } });
const page = await context.newPage();
const externalRequests = [];
page.on('request', r => { if (!r.url().startsWith(base) && !r.url().startsWith('data:') && !r.url().startsWith('blob:')) externalRequests.push(r.url()); });
await page.goto(`${base}/`, { waitUntil: 'networkidle' });
await page.getByRole('textbox', { name: /描述你想生成的应用/ }).fill('生成一个极简中文待办清单');
await page.getByRole('button', { name: '开始生成' }).click();
await page.waitForURL(/\/projects\/[0-9a-f-]{36}/i, { timeout: 20000 });
await page.getByTestId('agent-card-engineer').getByText('已完成').waitFor({ timeout: 45000 });
const overflowWorkbench = await page.evaluate(() => [...document.querySelectorAll('body *')].filter(e => e.scrollWidth > e.clientWidth + 1 && getComputedStyle(e).overflowX !== 'visible').map(e => ({ tag: e.tagName, cls: typeof e.className === 'string' ? e.className.slice(0, 100) : '', text: (e.innerText || '').slice(0, 70), scrollWidth: e.scrollWidth, clientWidth: e.clientWidth })).slice(0, 20));
await page.getByRole('button', { name: '展开详情' }).first().click();
await page.screenshot({ path: `${out}/workbench-expanded.png`, fullPage: false });
await page.getByTestId('workbench-tab-code').click();
await page.getByText('src/App.tsx', { exact: true }).last().waitFor({ state: 'visible', timeout: 30000 });
await page.getByText(/import \{ useState \}/).waitFor({ state: 'visible', timeout: 30000 });
await page.screenshot({ path: `${out}/code.png`, fullPage: false });
const codeText = await page.locator('main').innerText();
await page.getByTestId('workbench-tab-preview').click();
await page.getByTestId('preview-pane').waitFor({ state: 'visible' });
await page.waitForFunction(() => document.querySelector('[data-testid="preview-pane"]')?.getAttribute('data-preview-painted') === 'true', { timeout: 45000 });
await page.screenshot({ path: `${out}/preview.png`, fullPage: false });
const sandbox = await page.getByTestId('preview-iframe').getAttribute('sandbox');
const probe = await page.getByTestId('preview-paint-probe').innerText();
const result = { projectUrl: page.url(), sandbox, probe, sourceVisible: /import \{ useState \}/.test(codeText), externalRequests, overflowWorkbench };
await fs.writeFile(`${out}/visual-probes.json`, JSON.stringify(result, null, 2));
await browser.close();
console.log(JSON.stringify(result, null, 2));
