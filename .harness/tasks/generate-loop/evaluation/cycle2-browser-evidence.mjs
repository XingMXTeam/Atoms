import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
const root = '/Users/felix/Documents/atoms-worktrees/demo';
const base = 'http://localhost:3000';
const out = `${root}/.harness/tasks/generate-loop/evidence/c2-20261123`;
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1280, height: 800 } });
const page = await context.newPage();
const externalRequests = [];
page.on('request', request => { if (!request.url().startsWith(base) && !request.url().startsWith('data:') && !request.url().startsWith('blob:')) externalRequests.push(request.url()); });
await page.goto(`${base}/`, { waitUntil: 'networkidle' });
await page.getByRole('textbox', { name: /描述你想生成的应用/ }).fill('生成一个极简中文待办清单');
await page.getByRole('button', { name: '开始生成' }).click();
await page.waitForURL(/\/projects\/[0-9a-f-]{36}/i, { timeout: 20000 });
await page.getByTestId('agent-card-engineer').getByText('已完成').waitFor({ timeout: 45000 });
await page.screenshot({ path: `${out}/workbench.png`, fullPage: false });
const cards = await page.locator('[data-testid^="agent-card-"]').count();
const timelinePayloadButtons = await page.locator('[data-testid^="agent-card-"] button').count();
await page.getByTestId('workbench-tab-code').click();
await page.screenshot({ path: `${out}/code.png`, fullPage: false });
const codeText = await page.locator('main').innerText();
await page.getByTestId('workbench-tab-preview').click();
await page.getByTestId('preview-pane').getAttribute('data-preview-painted').then(async v => { if (v !== 'true') await page.getByTestId('preview-paint-probe').waitFor({ state: 'visible', timeout: 30000 }); });
await page.screenshot({ path: `${out}/preview.png`, fullPage: false });
const iframe = page.getByTestId('preview-iframe');
const sandbox = await iframe.getAttribute('sandbox');
const paintProbe = await page.getByTestId('preview-paint-probe').innerText().catch(() => '');
const finishedStatus = await page.getByTestId('workbench-run-status').getAttribute('data-run-status');
const successHasContinue = await page.getByRole('button', { name: '继续' }).count();
await page.goto(`${base}/`);
await page.getByRole('textbox', { name: /描述你想生成的应用/ }).fill('双击提交探测');
const createResponses = [];
page.on('response', response => { if (response.url().includes('/api/projects') && response.request().method() === 'POST') createResponses.push(response.status()); });
await page.getByRole('button', { name: '开始生成' }).dblclick();
await page.waitForURL(/\/projects\/[0-9a-f-]{36}/i, { timeout: 20000 });
const doubleSubmitUrl = page.url();
await page.goto(`${base}/`);
const prompt = page.getByRole('textbox', { name: /描述你想生成的应用/ });
const longValue = `${'长'.repeat(1100)} 😀 مرحبا`;
await prompt.fill(longValue);
const longInputLength = await prompt.inputValue().then(v => v.length);
const longSubmitDisabled = await page.getByRole('button', { name: '开始生成' }).isDisabled();
await prompt.fill('');
const emptySubmitDisabled = await page.getByRole('button', { name: '开始生成' }).isDisabled();
const apiLog = [];
const successResp = await context.request.post(`${base}/api/projects`, { data: { prompt: 'API契约探测' } });
apiLog.push({ case: 'POST /api/projects valid prompt', status: successResp.status(), body: (await successResp.text()).slice(0, 600) });
const emptyResp = await context.request.post(`${base}/api/projects`, { data: { prompt: '' } });
apiLog.push({ case: 'POST /api/projects empty prompt', status: emptyResp.status(), body: (await emptyResp.text()).slice(0, 600) });
const malformedResp = await context.request.post(`${base}/api/projects`, { data: 'not-json', headers: { 'content-type': 'application/json' } });
apiLog.push({ case: 'POST /api/projects malformed JSON', status: malformedResp.status(), body: (await malformedResp.text()).slice(0, 600) });
const report = { projectUrl: doubleSubmitUrl, timelineCards: cards, payloadButtons: timelinePayloadButtons, finishedStatus, successHasContinue, sandbox, paintProbe, codeHasFileContent: /\.tsx|\.ts|\.css|function|return/.test(codeText), externalRequests, exploratory: { doubleSubmitResponses: createResponses, longInputLength, longSubmitDisabled, emptySubmitDisabled }, api: apiLog };
await fs.writeFile(`${out}/journey.json`, JSON.stringify(report, null, 2));
await browser.close();
console.log(JSON.stringify(report, null, 2));
