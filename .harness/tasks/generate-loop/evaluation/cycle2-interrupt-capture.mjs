import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
const base = 'http://localhost:3000';
const out = '/Users/felix/Documents/atoms-worktrees/demo/.harness/tasks/generate-loop/evidence/c2-20261123';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
await page.goto(`${base}/`);
await page.evaluate(() => localStorage.setItem('atoms.generate-loop.stageDelayMs', '1200'));
await page.getByRole('textbox', { name: /描述你想生成的应用/ }).fill('做一个会中断的演示应用');
await page.getByRole('button', { name: '开始生成' }).click();
await page.waitForURL(/\/projects\/[0-9a-f-]{36}/i, { timeout: 20000 });
await page.waitForFunction(() => typeof window.__ATOMS_ABORT_SSE__ === 'function', { timeout: 15000 });
await page.evaluate(() => window.__ATOMS_ABORT_SSE__());
await page.getByRole('button', { name: '继续' }).waitFor({ state: 'visible', timeout: 15000 });
await page.screenshot({ path: `${out}/interrupted.png`, fullPage: false });
const status = await page.getByTestId('agent-timeline').getAttribute('data-run-status');
const recovery = await page.getByRole('button', { name: '继续' }).innerText();
await fs.writeFile(`${out}/interrupt.json`, JSON.stringify({ status, recovery, url: page.url() }, null, 2));
await browser.close();
console.log(JSON.stringify({ status, recovery }));
