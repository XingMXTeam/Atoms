import { createRequire } from "node:module";
const require = createRequire(`${process.cwd()}/package.json`);
const { chromium } = require("@playwright/test");
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1280, height: 800 } });
const page = await context.newPage();
await page.goto("http://127.0.0.1:3000/");
await page.evaluate(() => localStorage.setItem("atoms.generate-loop.stageDelayMs", "1200"));
await page.getByRole("textbox", { name: /描述你想生成的应用/ }).fill("中断恢复截图检查");
await page.getByRole("button", { name: "开始生成" }).click();
await page.waitForURL(/\/projects\/[0-9a-f-]{36}/i, { timeout: 15000 });
await page.waitForFunction(() => typeof window.__ATOMS_ABORT_SSE__ === "function", { timeout: 10000 });
await page.evaluate(() => window.__ATOMS_ABORT_SSE__());
await page.getByRole("button", { name: "继续" }).waitFor({ timeout: 10000 });
await page.screenshot({ path: ".harness/tasks/generate-loop/evidence/c2-confirm-20261123/workbench-interrupted.png", fullPage: true });
const result = { status: await page.getByTestId("agent-timeline").getAttribute("data-run-status"), continueVisible: await page.getByRole("button", { name: "继续" }).isVisible() };
console.log(JSON.stringify(result));
await context.close();
await browser.close();
